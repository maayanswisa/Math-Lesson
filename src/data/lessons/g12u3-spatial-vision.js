/** פריסה על משבצות: cells — [[עמודה, שורה, תווית?]]; כל משבצת היא פאה. */
const net = (cells, color = 'rgba(13,110,110,0.16)', size = 26) => {
  const cols = Math.max(...cells.map((p) => p[0])) + 1;
  const rows = Math.max(...cells.map((p) => p[1])) + 1;
  const body = cells
    .map(
      ([x, y, t]) =>
        `<rect x="${2 + x * size}" y="${2 + y * size}" width="${size}" height="${size}" fill="${color}" stroke="#0d6e6e" stroke-width="1.6"/>` +
        (t ? `<text x="${2 + x * size + size / 2}" y="${2 + y * size + size / 2 + 5}" text-anchor="middle" font-size="13" font-weight="700" fill="#1a2b3c">${t}</text>` : ''),
    )
    .join('');
  return `<svg viewBox="0 0 ${cols * size + 4} ${rows * size + 4}" width="${cols * size + 4}" xmlns="http://www.w3.org/2000/svg" style="direction:ltr">${body}</svg>`;
};

