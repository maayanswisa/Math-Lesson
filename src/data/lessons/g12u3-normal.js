const BELL = (() => {
  const W = 360;
  const base = 128;
  const X = (z) => 30 + ((z + 3.6) / 7.2) * (W - 60);
  const Y = (z) => base - 104 * Math.exp((-z * z) / 2);
  const curve = Array.from({ length: 145 }, (_, i) => -3.6 + (7.2 * i) / 144)
    .map((z, i) => `${i ? 'L' : 'M'}${X(z).toFixed(1)} ${Y(z).toFixed(1)}`)
    .join(' ');
  const band = (a, b, fill) => {
    const pts = Array.from({ length: 31 }, (_, i) => a + ((b - a) * i) / 30);
    return `<path d="M${X(a).toFixed(1)} ${base} ${pts.map((z) => `L${X(z).toFixed(1)} ${Y(z).toFixed(1)}`).join(' ')} L${X(b).toFixed(1)} ${base} Z" fill="${fill}"/>`;
  };
  const shades = ['rgba(13,110,110,0.32)', 'rgba(13,110,110,0.2)', 'rgba(13,110,110,0.1)'];
  let s = `<svg viewBox="0 0 ${W} 168" width="360" xmlns="http://www.w3.org/2000/svg" style="direction:ltr">`;
  [0, 1, 2].forEach((k) => {
    s += band(k, k + 1, shades[k]) + band(-k - 1, -k, shades[k]);
  });
  s += `<path d="${curve}" fill="none" stroke="#0d6e6e" stroke-width="2.2"/>`;
  s += `<line x1="22" y1="${base}" x2="${W - 22}" y2="${base}" stroke="#1a2b3c" stroke-width="1.2"/>`;
  const labels = ['μ−3σ', 'μ−2σ', 'μ−σ', 'μ', 'μ+σ', 'μ+2σ', 'μ+3σ'];
  labels.forEach((t, i) => {
    const z = i - 3;
    s += `<line x1="${X(z)}" y1="${z === 0 ? Y(0) : Y(z)}" x2="${X(z)}" y2="${base + 4}" stroke="#1a2b3c" stroke-width="${z === 0 ? 1.4 : 0.9}" stroke-dasharray="${z === 0 ? '' : '3 2'}"/>`;
    s += `<text x="${X(z)}" y="${base + 16}" text-anchor="middle" font-size="10.5" font-weight="700" fill="#1a2b3c">${t}</text>`;
  });
  const pct = [
    [0.5, '34.13%', 96],
    [1.5, '13.59%', 116],
    [2.5, '2.14%', 122],
  ];
  pct.forEach(([z, t, y]) => {
    s += `<text x="${X(z)}" y="${y}" text-anchor="middle" font-size="10" font-weight="700" fill="#0a5555">${t}</text>`;
    s += `<text x="${X(-z)}" y="${y}" text-anchor="middle" font-size="10" font-weight="700" fill="#0a5555">${t}</text>`;
  });
  s += `<text x="${X(3.3)}" y="${base - 10}" text-anchor="middle" font-size="9.5" font-weight="700" fill="#c45c48">0.13%</text>`;
  s += `<text x="${X(-3.3)}" y="${base - 10}" text-anchor="middle" font-size="9.5" font-weight="700" fill="#c45c48">0.13%</text>`;
  return `<div class='diagram-box'>${s}</svg></div>`;
})();

