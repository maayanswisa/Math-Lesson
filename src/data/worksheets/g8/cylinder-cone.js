const { svg, label, INK, ACCENT, SHADE } = svgParts;
const PI = 3.14;

/** משבצת בקירוב: סובלנות קטנה, כדי שגם π מדויק יותר (3.1416) יתקבל. */
const approx = (x) => `[[n:${round(x, 2)}~${round(Math.abs(x) * 0.002 + 0.01, 2)}]]`;

/** שטח הפנים חלקי π: שני בסיסים ועוד המעטפת. */
const surf = (r, h) => 2 * r * r + 2 * r * h;

// היחידה כתובה בתווית שלפני המשבצת — כך היא נשארת צמודה למשבצת שלה גם כשהשורה נשברת
const net = (r, h) => ({
  q: m`גליל: רדיוס $${r}$ ס״מ, גובה $${h}$ ס״מ. מה המידות של מלבן המעטפת?`,
  a: m`צלע אחת (ס״מ): [[${h}]] $\qquad$ הצלע השנייה (ס״מ): ${approx(2 * PI * r)}`,
});

const cylinder = (r, h, given = 'r') => ({
  q: given === 'd' ? m`גליל: קוטר $${2 * r}$ ס״מ, גובה $${h}$ ס״מ` : m`גליל: רדיוס $${r}$ ס״מ, גובה $${h}$ ס״מ`,
  a: m`נפח (סמ״ק): ${approx(PI * r * r * h)} $\qquad$ מעטפת (סמ״ר): ${approx(2 * PI * r * h)} $\qquad$ שטח פנים (סמ״ר): ${approx(PI * surf(r, h))}`,
});

const cone = (r, h) => ({
  q: m`חרוט: רדיוס $${r}$ ס״מ, גובה $${h}$ ס״מ`,
  a: m`נפח (סמ״ק): ${approx((PI * r * r * h) / 3)} $\qquad$ שטח החתך הצירי (סמ״ר): [[${r * h}]]`,
});

