import { m, lin, round, coordPlane, ineqItem } from '../helpers.js';

/** קריאת m ו-b מתוך המשוואה. tex — צורה אחרת לכתוב את אותה פונקציה (4 - 2x). */
const mb = (a, b, tex = lin(a, b)) => ({ q: m`$y = ${tex}$`, a: m`$m =$ [[${a}]] $\qquad b =$ [[${b}]]` });

const TREND = ['עולה', 'יורדת', 'קבועה'];
const trend = (a, b) => ({ q: m`$y = ${lin(a, b)}$`, options: TREND, answer: a > 0 ? 0 : a < 0 ? 1 : 2 });

const table = (a, b, xs) => ({
  q: m`$y = ${lin(a, b)}$`,
  a: xs.map((x) => m`$x = ${x}:\; y =$ [[${round(a * x + b)}]]`).join(m` $\qquad$ `),
});

/** נקודות החיתוך עם הצירים: (0, b) ו-(-b/m, 0). */
const axes = (a, b) => ({
  q: m`$y = ${lin(a, b)}$`,
  a: m`$(0,\,$ [[${b}]] $)\qquad($ [[${round(-b / a)}]] $,\,0)$`,
});

const graph = (a, b) => ({ q: '', figure: coordPlane({ lines: [{ m: a, b }] }), a: m`$m =$ [[${a}]] $\qquad b =$ [[${b}]]` });

const onLine = (a, b, x, y) => ({
  q: m`האם הנקודה $(${x}, ${y})$ נמצאת על הישר $y = ${lin(a, b)}$?`,
  options: ['כן', 'לא'],
  answer: a * x + b === y ? 0 : 1,
});

