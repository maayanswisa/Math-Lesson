import { m, round } from '../helpers.js';

/** משוואה עם בדיקה: lhs(x) === rhs(x) בפתרון. */
function eq(tex, sol, lhs, rhs) {
  if (Math.abs(lhs(sol) - rhs(sol)) > 1e-9) throw new Error(`${sol} does not solve ${tex}`);
  return { q: m`$${tex}$ $\qquad x =$ [[${sol}]]` };
}

/** |ax + b| = c — שני פתרונות. */
function absEq(tex, a, b, c) {
  const [s1, s2] = [(c - b) / a, (-c - b) / a].map(round).sort((p, q) => q - p);
  return { q: m`$${tex}$`, a: m`הפתרון הגדול: [[${s1}]] $\quad$ הפתרון הקטן: [[${s2}]]` };
}

/** מערכת a1x + b1y = c1, a2x + b2y = c2 עם פתרון (x, y) — המספרים בצד ימין מחושבים. */
function system([a1, b1], [a2, b2], [x, y]) {
  const row = (a, b) => {
    const t = (k, v) => (k === 1 ? v : k === -1 ? `-${v}` : `${k}${v}`);
    const yPart = b === 0 ? '' : ` ${b < 0 ? '-' : '+'} ${t(Math.abs(b), 'y')}`;
    return `${a === 0 ? '' : t(a, 'x')}${yPart} &= ${a * x + b * y}`;
  };
  return {
    q: m`$\begin{cases} ${row(a1, b1)} \\ ${row(a2, b2)} \end{cases}$`,
    a: m`$x =$ [[${x}]] $\qquad y =$ [[${y}]]`,
  };
}

