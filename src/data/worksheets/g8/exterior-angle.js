const adjacent = (inner) => ({ q: m`זווית פנימית $${inner}°$ ← הזווית החיצונית לידה: [[${180 - inner}]] $°$` });

/** משפט הזווית החיצונית: שתי הזוויות הרחוקות → הזווית החיצונית. */
const extFromRemote = (a, b) => ({ q: m`הזוויות הפנימיות הרחוקות: $${a}°$ ו-$${b}°$ ← הזווית החיצונית: [[${a + b}]] $°$` });
const remoteFromExt = (ext, a) => ({ q: m`זווית חיצונית $${ext}°$, ואחת הזוויות הרחוקות $${a}°$ ← הזווית הרחוקה השנייה: [[${ext - a}]] $°$` });

const regularExt = (n) => ({ q: m`${NAMES[n]}: זווית חיצונית [[${round(360 / n)}]] $°$, זווית פנימית [[${round(180 - 360 / n)}]] $°$` });
function sidesFromExt(ext) {
  const n = 360 / ext;
  if (!Number.isInteger(n)) throw new Error('not a regular polygon');
  return { q: m`במצולע משוכלל כל זווית חיצונית היא $${ext}°$. כמה צלעות יש לו?`, a: `[[${n}]] צלעות` };
}

