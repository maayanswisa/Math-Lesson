import { m, num, fr, round, cmp } from '../helpers.js';

/** a × k / a : k עם תשובה מחושבת. */
const times = (a, k) => ({ q: m`$${num(a)} \times ${num(k)} =$ [[${round(a * k)}]]` });
const divide = (a, k) => ({ q: m`$${num(a)} : ${num(k)} =$ [[${round(a / k)}]]` });
const compare = (a, b, sa = String(a), sb = String(b)) => ({ q: m`$${sa}$ [[c:${cmp(a, b)}]] $${sb}$` });

const PLACES = ['אחדות', 'עשיריות', 'מאיות', 'אלפיות'];
const place = (n, digit, answer) => ({
  q: m`במספר $${n}$ הספרה $${digit}$ היא ספרת ה...`,
  options: PLACES,
  answer: PLACES.indexOf(answer),
});

