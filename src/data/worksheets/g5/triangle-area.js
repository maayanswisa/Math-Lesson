import { m, round, triangleFig } from '../helpers.js';

const area = (b, h) => round((b * h) / 2);

const areaItem = (b, h) => ({ q: m`בסיס $${b}$ ס״מ, גובה לבסיס $${h}$ ס״מ. השטח: [[${area(b, h)}]] סמ״ר` });
const figItem = (b, h, apex) => ({ q: '', figure: triangleFig({ base: b, height: h, apex }), a: m`שטח: [[${area(b, h)}]] סמ״ר` });

function missingHeight(S, b) {
  const h = (2 * S) / b;
  if (!Number.isInteger(h)) throw new Error('height not whole');
  return { q: m`שטח המשולש $${S}$ סמ״ר, והבסיס $${b}$ ס״מ. הגובה לבסיס: [[${h}]] ס״מ` };
}
function missingBase(S, h) {
  const b = (2 * S) / h;
  if (!Number.isInteger(b)) throw new Error('base not whole');
  return { q: m`שטח המשולש $${S}$ סמ״ר, והגובה $${h}$ ס״מ. הבסיס: [[${b}]] ס״מ` };
}

const perimeter = (a, b, c) => ({ q: m`צלעות המשולש: $${a}$, $${b}$, $${c}$ ס״מ. ההיקף: [[${round(a + b + c)}]] ס״מ` });

/** משולש ישר-זווית: ניצבים a, b ויתר c — שטח והיקף. */
const rightTriangle = (a, b, c) => ({
  q: '',
  figure: triangleFig({ base: a, height: b, apex: 0, sides: [c] }),
  a: m`שטח: [[${area(a, b)}]] סמ״ר · היקף: [[${a + b + c}]] ס״מ`,
});

