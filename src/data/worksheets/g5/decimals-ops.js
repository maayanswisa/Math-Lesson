import { m, fr, round, cmp, reduce } from '../helpers.js';

const add = (a, b) => ({ q: m`$${a} + ${b} =$ [[${round(a + b)}]]` });
const sub = (a, b) => ({ q: m`$${a} - ${b} =$ [[${round(a - b)}]]` });
/** a, b כמחרוזות כדי לשמור על אפסים בסוף (2.10). */
const compare = (a, b) => ({ q: m`$${a}$ [[c:${cmp(Number(a), Number(b))}]] $${b}$` });

const toWhole = (x) => ({ q: m`$${x} \approx$ [[${Math.round(x)}]]` });
const toTenths = (x) => ({ q: m`$${x} \approx$ [[${round(Math.round(round(x * 10)) / 10)}]]` });

/** עשרוני → שבר פשוט מצומצם. */
function decToFrac(s) {
  const places = s.split('.')[1].length;
  const [n, d] = reduce(Math.round(Number(s) * 10 ** places), 10 ** places);
  return { q: m`$${s} =$ [[fx:${n}/${d}]]` };
}
const fracToDec = (n, d) => ({ q: m`$${fr(n, d)} =$ [[${round(n / d)}]]` });

