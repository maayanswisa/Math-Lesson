import { m, fr, mixed, valueBlank } from '../helpers.js';

/**
 * מספר כ-[שלם, מונה, מכנה]. שבר רגיל: [0, n, d]; שלם: [w, 0, 1].
 * התשובה מחושבת כשבר מדויק (בלי נקודה צפה) ומוצגת במשבצת לפי הערך.
 */
const tex = ([w, n, d]) => (n === 0 ? `${w}` : w === 0 ? fr(n, d) : mixed(w, n, d));
const improper = ([w, n, d]) => [w * d + n, d];

function op(x, sign, y) {
  const [a, b] = improper(x);
  const [c, d] = improper(y);
  const num = sign === '+' ? a * d + c * b : a * d - c * b;
  if (num < 0) throw new Error('negative result');
  return { q: m`$${tex(x)} ${sign} ${tex(y)} =$ ${valueBlank(num, b * d)}` };
}
const add = (x, y) => op(x, '+', y);
const sub = (x, y) => op(x, '-', y);
const f = (n, d) => [0, n, d];

/** משבצת חסרה: x ± ? = target. */
function missing(x, sign, target) {
  const [a, b] = improper(x);
  const [c, d] = improper(target);
  const num = sign === '+' ? c * b - a * d : a * d - c * b;
  return { q: m`$${tex(x)} ${sign}$ ${valueBlank(num, b * d)} $= ${tex(target)}$` };
}

