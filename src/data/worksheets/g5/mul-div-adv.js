import { m, num, calc } from '../helpers.js';

const add = (a, b) => calc(m`${num(a)} + ${num(b)}`);
const sub = (a, b) => calc(m`${num(a)} - ${num(b)}`);
const mul = (a, b) => calc(m`${num(a)} \times ${num(b)}`);
function div(a, b) {
  if (a % b !== 0) throw new Error(`${a} : ${b} is not exact`);
  return calc(m`${num(a)} : ${num(b)}`);
}
/** חילוק עם שארית: a : b = מנה, שארית. */
const divRem = (a, b) => ({
  q: m`$${num(a)} : ${b} =$ [[${Math.floor(a / b)}]] שארית [[${a % b}]]`,
});

