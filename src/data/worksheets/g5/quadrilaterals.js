const SHAPES = ['מקבילית', 'מלבן', 'ריבוע', 'מעוין', 'דלתון', 'טרפז'];
const which = (q, shape) => {
  if (!SHAPES.includes(shape)) throw new Error(shape);
  return { q, options: SHAPES, answer: SHAPES.indexOf(shape) };
};

const TF = ['נכון', 'לא נכון'];
const tf = (q, truth) => ({ q, options: TF, answer: truth ? 0 : 1 });

const perimeter = (q, sides) => ({ q: m`${q}. ההיקף: [[${sides.reduce((a, b) => a + b, 0)}]] ס״מ` });

/** שלוש זוויות ידועות — הרביעית משלימה ל-360°. */
function fourthAngle(q, angles) {
  const x = 360 - angles.reduce((a, b) => a + b, 0);
  if (x <= 0 || x >= 360) throw new Error(`bad angles ${angles}`);
  return { q: m`${q} $${angles.map((a) => m`${a}^\circ`).join(',\\;')}$. הזווית הרביעית: [[${x}]] $^\circ$` };
}

