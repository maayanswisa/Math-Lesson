const vertexItem = (a, b, c) => {
  const [p, q] = vertex(a, b, c);
  return {
    q: m`$y=${poly([a, b, c])}$`,
    a: m`הקודקוד: $($ [[${p}]] $,\,$ [[${q}]] $)$ $\qquad$ חיתוך עם ציר $y$: [[${c}]]`,
  };
};

const rootsItem = (a, b, c) => {
  const [big, small] = roots(a, b, c);
  if (small === undefined) throw new Error('need two roots');
  return { q: m`$${poly([a, b, c])}=0$`, a: m`הפתרון הגדול: [[${big}]] $\qquad$ הפתרון הקטן: [[${small}]]` };
};

