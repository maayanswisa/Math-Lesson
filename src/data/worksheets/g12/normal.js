/** טווח בסטיות תקן ← טקסט: (−1, 2) ← "בין μ−σ לבין μ+2σ"; ±4 = "מעבר לכל". */
const at = (k) => (k === 0 ? '\\mu' : `\\mu${k > 0 ? '+' : '-'}${Math.abs(k) === 1 ? '' : Math.abs(k)}\\sigma`);
function range(from, to) {
  if (to === 4) return m`מעל $${at(from)}$`;
  if (from === -4) return m`מתחת ל-$${at(to)}$`;
  return m`בין $${at(from)}$ לבין $${at(to)}$`;
}
const percentIn = (from, to) => ({ q: range(from, to), a: m`האחוז: [[n:${pct(from, to)}~0.02]] $\%$` });

const zScore = (x, mean, sd) => ({ q: m`ממוצע $${mean}$, סטיית תקן $${sd}$, הערך $${x}$`, a: m`ציון התקן: ${exact((x - mean) / sd)}` });
const fromZ = (z, mean, sd) => ({ q: m`ממוצע $${mean}$, סטיית תקן $${sd}$, ציון התקן $${z}$`, a: m`הערך: ${exact(mean + z * sd)}` });

/** איפה המיקום היחסי גבוה יותר — לפי ציון התקן. */
function compareZ([s1, x1, m1, sd1], [s2, x2, m2, sd2]) {
  const z1 = (x1 - m1) / sd1;
  const z2 = (x2 - m2) / sd2;
  if (z1 === z2) throw new Error('equal z');
  return {
    q: m`ב${s1} — $${x1}$ (ממוצע $${m1}$, סטיית תקן $${sd1}$). ב${s2} — $${x2}$ (ממוצע $${m2}$, סטיית תקן $${sd2}$). איפה המיקום היחסי גבוה יותר?`,
    options: [`ב${s1}`, `ב${s2}`],
    answer: z1 > z2 ? 0 : 1,
  };
}

