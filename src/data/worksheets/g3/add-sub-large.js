const add = (a, b) => calc(m`${num(a)} + ${num(b)}`);
const sub = (a, b) => calc(m`${num(a)} - ${num(b)}`);

function word(q, answer, unit, check) {
  if (!check(answer)) throw new Error(`answer ${answer} does not fit: ${q}`);
  return { q, a: m`[[${answer}]] ${unit}` };
}

const estimate = (tex, options, answer) => ({ q: m`$${tex}$ — בערך...`, options: options.map((o) => m`$${num(o)}$`), answer });

