import { round } from '../helpers.js';
import { big, grow, m, near, tf } from './shared.js';

/** p% (חיובי — גדילה, שלילי — דעיכה) ← המקדם q */
const qItem = (p) => ({ q: p > 0 ? m`גדילה של $${p}\%$` : m`דעיכה של $${-p}\%$`, a: m`$q =$ [[${round(1 + p / 100, 4)}]]` });

const amount = (what, a0, p, t, unit, units) => ({
  q: m`${what}: בהתחלה $${big(a0)}$, ${p > 0 ? 'גדילה' : 'דעיכה'} של $${Math.abs(p)}\%$ בכל ${unit}. כמה יהיו אחרי ${units}?`,
  a: m`הכמות: ${near(grow(a0, 1 + p / 100, t))}`,
});

/** הזמן השלם הראשון שבו A₀·qᵗ עובר את היעד (גדילה) או יורד מתחתיו (דעיכה). */
function firstTime(q, ratio) {
  for (let t = 1; t < 200; t++) if (q > 1 ? q ** t > ratio : q ** t < ratio) return t;
  throw new Error('no time');
}

