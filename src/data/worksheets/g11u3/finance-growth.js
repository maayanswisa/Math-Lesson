import { big, grow, m, near, tf } from './shared.js';

const saving = (m0, p, n) => ({ q: m`מפקידים $${big(m0)}$ ₪ בריבית של $${p}\%$ בשנה, למשך $${n}$ שנים.`, a: m`הסכום (₪): ${near(grow(m0, 1 + p / 100, n))}` });
const depreciation = (what, m0, p, n) => ({ q: m`${what} שעולה $${big(m0)}$ ₪ מאבד $${p}\%$ מערכו בכל שנה. מה ערכו אחרי $${n}$ שנים?`, a: m`הערך (₪): ${near(grow(m0, 1 - p / 100, n))}` });

/** השנה השלמה הראשונה שבה M₀·qⁿ עובר את היעד (או יורד מתחתיו). */
function firstYear(q, ratio) {
  for (let n = 1; n < 200; n++) if (q > 1 ? q ** n > ratio : q ** n < ratio) return n;
  throw new Error('no year');
}

