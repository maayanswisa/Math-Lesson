const sdItem = (xs) => ({ q: m`$${list(xs)}$`, a: m`הממוצע: ${exact(mean(xs))} $\qquad$ סטיית התקן: ${exact(sd(xs))}` });

/** טבלת שכיחויות: [[ערך, שכיחות], ...] */
const tableItem = (rows) => {
  const xs = rows.flatMap(([x, f]) => Array(f).fill(x));
  return {
    q: rows.map(([x, f]) => m`$${x}$ — $${f}$ פעמים`).join(' $\\quad$ '),
    a: m`מספר הנתונים: [[${xs.length}]] $\qquad$ הממוצע: ${exact(mean(xs))} $\qquad$ סטיית התקן: ${exact(sd(xs))}`,
  };
};

