/**
 * בעיית קיצון: target(x) על התחום [a, b]. הפתרון x0 מאומת בחיפוש מספרי,
 * והמשבצות מקבלות ערכים שמחושבים מאותה פונקציה.
 */
function optimum(q, target, [a, b], kind, x0, blanks) {
  const found = argExtreme(target, a, b, kind);
  if (Math.abs(found - x0) > 1e-3 * Math.max(1, Math.abs(x0))) throw new Error(`optimum is at ${found}, not ${x0}: ${q}`);
  return { q, a: blanks(x0) };
}

