/** בעיית קיצון במרחב: x ו-value נבדקים מול חיפוש מספרי. */
function optimum(text, f, lo, hi, kind, x, value, labels, figure) {
  const found = argExtreme(f, lo, hi, kind);
  if (Math.abs(found - x) > 1e-3 || Math.abs(f(x) - value) > 1e-6) throw new Error(`wrong optimum for: ${text}`);
  const item = { q: text, a: m`${labels[0]} $=$ ${exact(x)} $\;\cdot\;$ ${labels[1]} $=$ ${exact(value)}` };
  return figure ? { ...item, figure } : item;
}

