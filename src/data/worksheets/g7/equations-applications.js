/**
 * שאלה מילולית: check(x) חייב להחזיר true — כך מוודאים שהנתונים
 * בסיפור באמת מובילים לתשובה.
 */
function word(q, a, check) {
  if (!check()) throw new Error(`check failed: ${q}`);
  return { q, a };
}

