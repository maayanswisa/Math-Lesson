/** זוויות צמודות: נתונה אחת, מוצאים את השנייה. */
const adjacent = (a) => ({ q: '', figure: adjacentFig(a, [`${a}°`, '?']), a: m`$? =$ [[${180 - a}]] $°$` });

/** ישרים נחתכים: נתונה זווית אחת, מוצאים את שלוש האחרות (תרגיל עם השרטוט, משבצת לכל זווית). */
const cross = (title, a) => ({
  title,
  cols: 3,
  figure: crossFig(a, [`${a}°`, 'β', 'γ', 'δ']),
  items: [
    { q: m`$\beta =$ [[${180 - a}]]` },
    { q: m`$\gamma =$ [[${a}]]` },
    { q: m`$\delta =$ [[${180 - a}]]` },
  ],
});

const bisector = (a) => ({ q: m`חוצה זווית של $${a}°$ מחלק אותה לשתי זוויות של`, a: m`[[${a / 2}]] $°$` });
const fromHalf = (h) => ({ q: m`חוצה זווית יצר זווית של $${h}°$. הזווית כולה:`, a: m`[[${2 * h}]] $°$` });

/** זוויות צמודות עם x: למשל x ו-2x. */
function adjX(k1, c1, k2, c2) {
  // k1·x + c1 + k2·x + c2 = 180
  const x = (180 - c1 - c2) / (k1 + k2);
  if (!Number.isInteger(x)) throw new Error('x must be whole');
  const term = (k, c) => `${k === 1 ? '' : k}x${c ? (c > 0 ? ` + ${c}` : ` - ${-c}`) : ''}`;
  return {
    q: m`שתי זוויות צמודות: $${term(k1, c1)}$ ו-$${term(k2, c2)}$.`,
    a: m`$x =$ [[${x}]] · הזוויות: [[${k1 * x + c1}]] ו-[[${k2 * x + c2}]] מעלות`,
  };
}

