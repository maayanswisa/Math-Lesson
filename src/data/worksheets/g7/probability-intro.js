/** הערכת הסתברות משכיחות יחסית — כעשרוני. */
const estimate = (event, f, n) => ({ q: m`${event}: $${f}$ פעמים מתוך $${n}$ ניסויים. ההסתברות המשוערת:`, a: `[[${round(f / n, 4)}]]` });

/** כמה פעמים צפוי לקרות ב-N ניסויים חדשים? */
const expected = (p, N, q) => {
  const e = p * N;
  if (!Number.isInteger(round(e, 6))) throw new Error('expected count must be whole');
  return { q, a: `[[${round(e, 6)}]]` };
};

