/** הסתברות כשבר — כל שבר שווה ערך מתקבל, וגם 0 ו-1. */
export const probBlank = (fav, all) => {
  const [n, d] = reduce(fav, all);
  return d === 1 ? `[[${n}]]` : `[[f:${n}/${d}]]`;
};
const prob = (q, fav, all) => ({ q, a: probBlank(fav, all) });

/** שתי קוביות: כמה תוצאות מקיימות תנאי. */
function dice(q, cond) {
  let fav = 0;
  for (let a = 1; a <= 6; a++) for (let b = 1; b <= 6; b++) if (cond(a, b)) fav++;
  return prob(q, fav, 36);
}

