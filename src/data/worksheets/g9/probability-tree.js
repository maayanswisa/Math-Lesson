import { m, reduce, round } from '../helpers.js';
import { tf } from './shared.js';

const frac = (n, d) => {
  const [a, b] = reduce(n, d);
  return b === 1 ? `[[${a}]]` : `[[f:${a}/${b}]]`;
};

/**
 * שתי הוצאות משקית עם r אדומים ו-b כחולים — עם או בלי החזרה.
 * מחשבים בדיוק בשברים: P(אדום ואז אדום), P(שני צבעים שונים).
 */
function draws(r, b, replace) {
  const n = r + b;
  const second = replace ? n : n - 1;
  const rr = [r * (replace ? r : r - 1), n * second];
  const diff = [r * b + b * r, n * second];
  return {
    title: m`בשקית $${r}$ כדורים אדומים ו-$${b}$ כחולים. מוציאים שני כדורים ${replace ? '**עם החזרה**' : '**בלי החזרה**'}. מה ההסתברות...`,
    cols: 2,
    items: [
      { q: 'שהכדור הראשון אדום?', a: frac(r, n) },
      { q: 'ששני הכדורים אדומים?', a: frac(...rr) },
      { q: 'שהכדורים בצבעים שונים?', a: frac(...diff) },
      { q: 'ששני הכדורים כחולים?', a: frac(b * (replace ? b : b - 1), n * second) },
    ],
  };
}

