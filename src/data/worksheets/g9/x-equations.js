import { exact, tf } from './shared.js';

/** משוואה עם בדיקה: lhs(sol) === rhs(sol). */
function eq(tex, sol, lhs, rhs) {
  if (Math.abs(lhs(sol) - rhs(sol)) > 1e-9) throw new Error(`${sol} does not solve ${tex}`);
  return { q: m`$${tex}$ $\qquad x =$ ${exact(sol)}` };
}

function word(q, answer, unit, check) {
  if (!check(answer)) throw new Error(`answer ${answer} does not fit: ${q}`);
  return { q, a: m`[[${answer}]] ${unit}` };
}

