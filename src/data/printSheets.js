const pad = (n) => String(n).padStart(2, '0');

/** דפי התרגילים של הכיתה, לפי הסדר; מערך ריק אם אין. */
export function getPrintSheets(grade) {
  return SERIES[Number(grade)] ?? [];
}

export function hasPrintSheets(grade) {
  return getPrintSheets(grade).length > 0;
}

export const PRINT_SHEET_GRADES = Object.keys(SERIES).map(Number);

/** הנתיב לעמוד דפי התרגילים של הכיתה. */
export function printSheetsHref(grade) {
  return `/grade/${grade}/print-sheets`;
}

/** קובץ ה-PDF של דף אחד (שני עמודי תרגול ועמוד תשובות). */
export function sheetFile(grade, no) {
  return `/print-sheets/g${grade}/${pad(no)}.pdf`;
}

/** החוברות של הכיתה: 'student' — כל עמודי התרגול, 'answers' — כל דפי התשובות. */
export function bookletFile(grade, kind) {
  return `/print-sheets/g${grade}/${kind}.pdf`;
}
