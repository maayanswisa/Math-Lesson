const pad = (n) => String(n).padStart(2, '0');

/** מזהה הסדרה: הכיתה, ובחטיבה העליונה — הכיתה ומספר היחידות ('11-4'). */
const seriesKey = (grade, units) => (units ? `${Number(grade)}-${Number(units)}` : String(Number(grade)));
const folder = (grade, units) => (units ? `g${grade}-${units}u` : `g${grade}`);

/** דפי התרגילים של הכיתה (ושל רמת היחידות, אם יש), לפי הסדר; מערך ריק אם אין. */
export function getPrintSheets(grade, units = null) {
  return SERIES[seriesKey(grade, units)] ?? [];
}

export function hasPrintSheets(grade, units = null) {
  return getPrintSheets(grade, units).length > 0;
}

/** כל הסדרות: { grade, units } — units הוא null בכיתות שאין בהן רמות. */
export const PRINT_SHEET_SERIES = Object.keys(SERIES).map((k) => {
  const [grade, units] = k.split('-').map(Number);
  return { grade, units: units || null };
});

export const PRINT_SHEET_GRADES = [...new Set(PRINT_SHEET_SERIES.map((s) => s.grade))];

/** הנתיב לעמוד דפי התרגילים של הכיתה (או של רמת היחידות). */
export function printSheetsHref(grade, units = null) {
  return units ? `/grade/${grade}/units/${units}/print-sheets` : `/grade/${grade}/print-sheets`;
}

/** קובץ ה-PDF של דף אחד (שני עמודי תרגול ועמוד תשובות). */
export function sheetFile(grade, no, units = null) {
  return `/print-sheets/${folder(grade, units)}/${pad(no)}.pdf`;
}

/** החוברות: 'student' — כל עמודי התרגול, 'answers' — כל דפי התשובות. */
export function bookletFile(grade, kind, units = null) {
  return `/print-sheets/${folder(grade, units)}/${kind}.pdf`;
}

